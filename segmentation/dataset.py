"""SECOND semantic-change dataset, split by CDVQA pair id.

The split is the important part. SECOND ships its own train/test folders, but
those say nothing about CDVQA's split: every one of CDVQA's 2,968 scenes
lives inside SECOND's ``train/`` folder, and CDVQA re-split them 1600/400/968.
So the scene lists here come from the CDVQA image manifests, never from the
directory layout, and :func:`assert_split_disjoint` fails loudly if a test
scene ever reaches the training set.

That check is not ceremony. Every CDVQA answer was generated by rule from
these same label maps, so training on a test scene's labels is training on
the answer key -- accuracy would look excellent and mean nothing.
"""

from __future__ import annotations

import json
import os
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
import torch
from torch.utils.data import Dataset

from tools.change_analysis.cdvqa import N_CLASSES, decode_label

__all__ = [
    "IMAGENET_MEAN",
    "IMAGENET_STD",
    "SECONDChangeDataset",
    "assert_split_disjoint",
    "cdvqa_split_scenes",
]

IMAGENET_MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
IMAGENET_STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)


def cdvqa_split_scenes(cdvqa_root: str, split: str) -> List[str]:
    """Unique scene filenames in one CDVQA split, sorted.

    Reads only the image manifest: roughly sixteen entries share a scene, and
    the questions/answers are irrelevant to segmentation.
    """
    path = os.path.join(cdvqa_root, f"{split}_images.json")
    if not os.path.exists(path):
        raise FileNotFoundError(f"CDVQA image manifest not found: {path!r}")
    with open(path, "r", encoding="utf-8") as handle:
        entries = json.load(handle)["images"]
    return sorted({entry["file_name"] for entry in entries})


def assert_split_disjoint(
    train_scenes: Sequence[str], **held_out: Sequence[str]
) -> None:
    """Fail loudly if any held-out scene appears in the training set.

    CLAUDE.md section 2 requires this assertion explicitly. Each keyword
    argument is a named held-out split, so the error says which one leaked.
    """
    train = set(train_scenes)
    for name, scenes in held_out.items():
        overlap = sorted(train & set(scenes))
        assert not overlap, (
            f"{len(overlap)} scene(s) from the {name!r} split appear in the "
            f"training set. Every CDVQA answer was derived from these label "
            f"maps, so this is training on the answer key. "
            f"Offending scenes (first 10): {overlap[:10]!r}"
        )


class SECONDChangeDataset(Dataset):
    """Bi-temporal image pairs with their two semantic change maps.

    Returns ``(x, y1, y2)`` where ``x`` is the two images stacked on the
    channel axis as ``(6, H, W)`` float32, and ``y1``/``y2`` are ``(H, W)``
    int64 class maps in 0..6 with 0 meaning "unchanged".
    """

    def __init__(
        self,
        second_root: str,
        scenes: Sequence[str],
        augment: bool = False,
        seed: int = 0,
    ) -> None:
        self.second_root = second_root
        self.scenes = list(scenes)
        self.augment = augment
        self._rng = np.random.default_rng(seed)
        if not self.scenes:
            raise ValueError("dataset constructed with no scenes")

    def __len__(self) -> int:
        return len(self.scenes)

    def _load_image(self, folder: str, scene: str) -> np.ndarray:
        from PIL import Image

        path = os.path.join(self.second_root, folder, scene)
        array = np.asarray(Image.open(path).convert("RGB"), dtype=np.float32) / 255.0
        return (array - IMAGENET_MEAN) / IMAGENET_STD

    def __getitem__(self, index: int):
        scene = self.scenes[index]
        im1 = self._load_image("im1", scene)
        im2 = self._load_image("im2", scene)
        y1 = decode_label(os.path.join(self.second_root, "label1", scene))
        y2 = decode_label(os.path.join(self.second_root, "label2", scene))

        if self.augment:
            # Geometric only, and applied identically to all four arrays --
            # a flip applied to the image but not the label silently
            # destroys supervision. No colour jitter: the two dates already
            # differ radiometrically and that difference is the signal.
            if self._rng.random() < 0.5:
                im1, im2, y1, y2 = (np.ascontiguousarray(a[:, ::-1]) for a in (im1, im2, y1, y2))
            if self._rng.random() < 0.5:
                im1, im2, y1, y2 = (np.ascontiguousarray(a[::-1]) for a in (im1, im2, y1, y2))
            k = int(self._rng.integers(0, 4))
            if k:
                im1, im2 = np.rot90(im1, k, (0, 1)), np.rot90(im2, k, (0, 1))
                y1, y2 = np.rot90(y1, k, (0, 1)), np.rot90(y2, k, (0, 1))
                im1, im2, y1, y2 = (np.ascontiguousarray(a) for a in (im1, im2, y1, y2))

        x = np.concatenate(
            [im1.transpose(2, 0, 1), im2.transpose(2, 0, 1)], axis=0
        )
        return (
            torch.from_numpy(np.ascontiguousarray(x)).float(),
            torch.from_numpy(np.ascontiguousarray(y1)).long(),
            torch.from_numpy(np.ascontiguousarray(y2)).long(),
        )


def class_pixel_counts(
    second_root: str, scenes: Sequence[str], limit: Optional[int] = None
) -> Dict[int, int]:
    """Pixel count per class across ``scenes``, for inverse-frequency weights.

    Class 0 dominates at roughly 79%, so an unweighted loss can reach a good
    pixel accuracy while predicting "unchanged" almost everywhere. Measuring
    the imbalance is the prerequisite for deciding whether to correct it.
    """
    counts = {c: 0 for c in range(N_CLASSES)}
    for scene in list(scenes)[:limit]:
        for folder in ("label1", "label2"):
            labels = decode_label(os.path.join(second_root, folder, scene))
            values, found = np.unique(labels, return_counts=True)
            for value, count in zip(values.tolist(), found.tolist()):
                counts[int(value)] += int(count)
    return counts
