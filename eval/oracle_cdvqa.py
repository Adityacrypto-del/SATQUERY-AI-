"""Oracle test: apply the CDVQA rules to GROUND-TRUTH semantic change maps.

CDVQA's answers were generated by rule from SECOND's label1/label2. So
running our rule implementation against those same maps must reproduce the
gold answers at near-100%. Anything less is a bug in our arithmetic, our
question parsing, or our palette binding -- not a modelling problem.

This is the ceiling. Final accuracy is roughly this number multiplied by
segmentation quality, so measuring it before training is what makes a
mediocre final score attributable.

**These are semantic CHANGE maps, not land-cover maps.** Class 0 (white) is
"unchanged" and is identical in label1 and label2 -- verified at exactly
100% agreement across both SECOND folders. A land-cover class exists only on
pixels that changed: label1 says what the pixel was, label2 what it became.
So "area of class l" throughout means area of l *among changed pixels*.
"""

from __future__ import annotations

import argparse
import json
import os
from collections import Counter, defaultdict
from typing import Any, Dict, List, Optional

from eval.run_cdvqa import QUESTION_TYPES, load_cdvqa_split
from tools.change_analysis.cdvqa import (
    CLASS_NAMES,
    PALETTE,
    answer_question,
    decode_label,
    parse_question,
    question_side,
    ratio_bin,
)

__all__ = ["format_oracle", "run_oracle"]


def run_oracle(
    cdvqa_root: str,
    second_root: str,
    split: str = "Train",
    limit: Optional[int] = None,
) -> Dict[str, Any]:
    """Score the rule implementation against gold answers on ground truth."""
    samples = load_cdvqa_split(cdvqa_root, split)

    by_scene: Dict[str, List] = defaultdict(list)
    for sample in samples:
        by_scene[sample.pair_id].append(sample)

    scenes = sorted(by_scene)
    if limit is not None:
        scenes = scenes[:limit]

    hits: Dict[str, int] = {t: 0 for t in QUESTION_TYPES}
    totals: Dict[str, int] = {t: 0 for t in QUESTION_TYPES}
    unparsed: Dict[str, int] = {t: 0 for t in QUESTION_TYPES}
    confusion: Dict[str, Counter] = defaultdict(Counter)

    for scene in scenes:
        s1 = decode_label(os.path.join(second_root, "label1", scene))
        s2 = decode_label(os.path.join(second_root, "label2", scene))
        for sample in by_scene[scene]:
            question_type = sample.question_type
            totals[question_type] = totals.get(question_type, 0) + 1
            result = answer_question(
                sample.question, question_type, s1, s2
            )
            predicted = result.answer
            if predicted is None:
                unparsed[question_type] = unparsed.get(question_type, 0) + 1
                continue
            if predicted == sample.answer:
                hits[question_type] = hits.get(question_type, 0) + 1
            elif len(confusion[question_type]) < 4000:
                confusion[question_type][(sample.answer, predicted)] += 1

    per_type = {}
    for question_type in totals:
        n = totals[question_type]
        per_type[question_type] = {
            "n": n,
            "correct": hits.get(question_type, 0),
            "unparsed": unparsed.get(question_type, 0),
            "agreement": (hits.get(question_type, 0) / n) if n else None,
        }
    measured = [v["agreement"] for v in per_type.values() if v["agreement"] is not None]
    total_n = sum(totals.values())
    return {
        "scenes": len(scenes),
        "per_type": per_type,
        "average_agreement": (sum(measured) / len(measured)) if measured else None,
        "overall_agreement": (
            sum(hits.values()) / total_n if total_n else None
        ),
        "n": total_n,
        "confusion": {k: v.most_common(6) for k, v in confusion.items()},
    }


def format_oracle(report: Dict[str, Any]) -> str:
    lines = [
        f"ORACLE -- rules applied to ground-truth maps ({report['scenes']} scenes)",
        "-" * 68,
    ]
    for question_type, entry in report["per_type"].items():
        agreement = entry["agreement"]
        rendered = "NOT_MEASURED" if agreement is None else f"{agreement * 100:6.2f}%"
        flag = "  <-- BELOW 95%" if agreement is not None and agreement < 0.95 else ""
        lines.append(
            f"  {question_type:<22} {rendered:>13}  "
            f"(n={entry['n']:>6}, unparsed={entry['unparsed']}){flag}"
        )
    for label, key in (
        ("Average agreement", "average_agreement"),
        ("Overall agreement", "overall_agreement"),
    ):
        value = report[key]
        rendered = "NOT_MEASURED" if value is None else f"{value * 100:6.2f}%"
        lines.append(f"  {label:<22} {rendered:>13}")
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cdvqa-root", default="datasets/CDVQA")
    parser.add_argument(
        "--second-root", default="datasets/SECOND_raw/train",
        help="directory holding label1/ and label2/",
    )
    parser.add_argument("--split", default="Train")
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--out", default=None)
    args = parser.parse_args(argv)

    report = run_oracle(
        args.cdvqa_root, args.second_root, args.split, args.limit
    )
    print(format_oracle(report))
    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as handle:
            json.dump(
                {k: v for k, v in report.items() if k != "confusion"},
                handle, indent=2,
            )
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
